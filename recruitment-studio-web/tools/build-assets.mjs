// Usage: node tools/build-assets.mjs <folder with the unpacked npm packages>
// The folder must contain the `npm pack` output, unpacked into one directory
// per tarball (e.g. htm-3.1.1/package, lucide-static-1.58.0/package, ...).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkgRoot = process.argv[2];
if (!pkgRoot || !fs.existsSync(pkgRoot)) {
  console.error('Usage: node tools/build-assets.mjs <unpacked packages folder>');
  process.exit(1);
}

function pkg(prefix) {
  const dir = fs.readdirSync(pkgRoot).find((d) => d.startsWith(prefix) && !d.endsWith('.tgz'));
  if (!dir) throw new Error(`Package not found: ${prefix}`);
  return path.join(pkgRoot, dir, 'package');
}

