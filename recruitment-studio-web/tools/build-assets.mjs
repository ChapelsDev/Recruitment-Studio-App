function unicodeRanges(cssText) {
  // Each rule is preceded by a "/* <file name> */" comment.
  const ranges = {};
  for (const m of cssText.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{[^}]*?unicode-range:\s*([^;]+);/g)) {
    ranges[m[1]] = m[2].trim();
  }
  return ranges;
}

let fontBytes = 0;
// One family's @font-face rules, one per line.
function fontRules(font) {
  const dir = pkg(font.pkg);
  const files = path.join(dir, 'files');
  let out = '';
  if (font.variable) {
    const ranges = unicodeRanges(fs.readFileSync(path.join(dir, 'wght.css'), 'utf8'));
    for (const subset of SUBSETS) {
      const name = `${font.file}-${subset}-wght-normal`;
      const data = fs.readFileSync(path.join(files, `${name}.woff2`));
      fontBytes += data.length;
      out += `@font-face{font-family:'${font.family}';font-style:normal;font-display:block;font-weight:100 900;` +
        `src:url(data:font/woff2;base64,${data.toString('base64')}) format('woff2');unicode-range:${ranges[name]};}\n`;
    }
    return out;
  }
  for (const weight of font.weights) {
    const ranges = unicodeRanges(fs.readFileSync(path.join(dir, `${weight}.css`), 'utf8'));
    for (const subset of SUBSETS) {
      const name = `${font.file}-${subset}-${weight}-normal`;
      const data = fs.readFileSync(path.join(files, `${name}.woff2`));
      fontBytes += data.length;
      out += `@font-face{font-family:'${font.family}';font-style:normal;font-display:block;font-weight:${weight};` +
        `src:url(data:font/woff2;base64,${data.toString('base64')}) format('woff2');unicode-range:${ranges[name]};}\n`;
    }
  }
  return out;
}

const fontsFile = path.join(appDir, 'assets', 'fonts.css');
if (only) {
  const font = FONTS.find((f) => f.file === only);
  if (!font) { console.error(`--only: no font "${only}" in FONTS`); process.exit(1); }
  const kept = fs.readFileSync(fontsFile, 'utf8').split('\n').filter((l) => !l.includes(`font-family:'${font.family}'`)).join('\n');
  const rules = fontRules(font);
  fs.writeFileSync(fontsFile, kept + rules);
  console.log(`fonts.css: ${font.family} rebuilt (${(fontBytes / 1024).toFixed(0)} KB of woff2); nothing else touched`);
  process.exit(0);
}
let css = '/* Generated by tools/build-assets.mjs - do not edit. Fonts: SIL OFL 1.1, see licenses/. */\n';
for (const font of FONTS) css += fontRules(font);
fs.writeFileSync(fontsFile, css);

