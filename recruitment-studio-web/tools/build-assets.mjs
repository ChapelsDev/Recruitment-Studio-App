const n = (v) => Number(v);
function attrs(tag) {
  const out = {};
  for (const m of tag.matchAll(/([a-zA-Z][a-zA-Z0-9:-]*)="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}
function toPath(el, a) {
  switch (el) {
    case 'path': return a.d;
    case 'circle': {
      const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
    }
    case 'ellipse': {
      const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case 'rect': {
      const x = n(a.x || 0), y = n(a.y || 0), w = n(a.width), h = n(a.height);
      let rx = a.rx != null ? n(a.rx) : (a.ry != null ? n(a.ry) : 0);
      let ry = a.ry != null ? n(a.ry) : rx;
      rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}` +
        `h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
    }
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return el === 'polygon' ? d + 'Z' : d;
    }
    default: throw new Error(`Unsupported SVG element <${el}>`);
  }
}
// A path that starts with a relative "m" is absolute on its own, but not once
// it is appended to the previous element's path: make that first move absolute
// (the coordinates that follow it stay relative line-tos, hence the "l").
const NUM = '[-+]?(?:\\d*\\.\\d+|\\d+\\.?)(?:[eE][-+]?\\d+)?';
const LEADING_REL_MOVE = new RegExp(`^\\s*m\\s*(${NUM})[\\s,]*(${NUM})`);
function absoluteStart(d) {
  const m = LEADING_REL_MOVE.exec(d);
  if (!m) return d;
  const rest = d.slice(m[0].length).replace(/^[\s,]+/, '');
  return `M${m[1]} ${m[2]}` + (/^[-+.\d]/.test(rest) ? `l${rest}` : rest);
}
const iconDir = path.join(pkg('lucide-static'), 'icons');
function iconPath(name) {
  const svg = fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8');
  const parts = [];
  for (const m of svg.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*)\/?>/g)) {
    parts.push(absoluteStart(toPath(m[1], attrs(m[2]))));
  }
  if (!parts.length) throw new Error(`No drawable elements in ${name}`);
  return parts.join('');
}
